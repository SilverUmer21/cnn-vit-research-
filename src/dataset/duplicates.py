# Finds exact and near-duplicate images. Read-only on the data.
# Usage: python -I src/dataset/duplicates.py <data_root> <reports_dir> <scratch_dir>
import hashlib
import io
import re
import sys
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor

import numpy as np
import pandas as pd
import torch
from PIL import Image, ImageDraw

SEED = 42
TOPK = 4
RMS_KEEP = 12.0            # candidate pairs above this grayscale RMS are discarded
BIN_EDGES = [0, 0.5, 1, 2, 3, 4, 6, 8, 12]
CHUNK = 1024
EXCLUDED = {  # outlier documented in reports/audit.md (not a lab leaf image)
    "train/Pepper,_bell___healthy/42f083e2-272d-4f83-ad9a-573ee90e50ec___"
    "Screen Shot 2015-05-06 at 4.01.13 PM.png",
}
NAME_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-"
                     r"[0-9a-fA-F]{12}___(?P<orig>.+)$")


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(lines)


def load(path):
    data = path.read_bytes()
    md5 = hashlib.md5(data).hexdigest()
    with Image.open(io.BytesIO(data)) as im:
        im = im.convert("RGB")
        if im.size != (256, 256):
            im = im.resize((256, 256), Image.LANCZOS)
        thumb = np.asarray(im.reduce(8), dtype=np.uint8)   # 32 x 32 x 3
    return md5, thumb


def tf_np(a, t):
    # flip/rotate every image in the batch (t is 0 to 7)
    out = np.rot90(a, t % 4, axes=(1, 2))
    return out[:, :, ::-1] if t >= 4 else out


def tf_torch(g, t):
    # same transform as tf_np, for torch tensors
    out = torch.rot90(g, t % 4, dims=(1, 2))
    return torch.flip(out, dims=(2,)) if t >= 4 else out


def mad32(thumbs, i, j, t):
    # mean absolute difference between thumb i and the transformed thumb j
    a = thumbs[i].astype(np.int16)
    b = tf_np(thumbs[j][None], t)[0].astype(np.int16)
    return float(np.abs(a - b).mean())


def best_mad(thumbs, i, j):
    vals = [mad32(thumbs, i, j, t) for t in range(8)]
    t = int(np.argmin(vals))
    return vals[t], t


def main():
    root = Path(sys.argv[1]).resolve()
    reports = Path(sys.argv[2]).resolve()
    scratch = Path(sys.argv[3]).resolve()
    if root in reports.parents or root in scratch.parents:
        sys.exit("refusing to write inside the data root")
    reports.mkdir(parents=True, exist_ok=True)
    scratch.mkdir(parents=True, exist_ok=True)

    rels = sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file())
    rels = [r for r in rels if r not in EXCLUDED]
    N = len(rels)
    df = pd.DataFrame({"path": rels})
    df["split"] = df["path"].str.split("/").str[0]
    df["cls"] = df["path"].str.split("/").str[1]
    df["fname"] = df["path"].str.split("/").str[2]
    stems = df["fname"].map(lambda f: Path(f).stem)
    orig = [(m.group("orig") if (m := NAME_RE.match(s)) else s) for s in stems]
    df["key"] = [re.sub(r"\s+", " ", o).strip().lower() for o in orig]
    print(f"images analysed: {N} (excluded: {len(EXCLUDED)})", flush=True)

    # load: md5 + thumbnails
    md5s, thumbs = [None] * N, np.zeros((N, 32, 32, 3), dtype=np.uint8)
    with ThreadPoolExecutor(max_workers=8) as pool:
        for i, (m, th) in enumerate(pool.map(load, [root / r for r in rels]), 0):
            md5s[i], thumbs[i] = m, th
            if (i + 1) % 10000 == 0:
                print(f"  loaded {i + 1}/{N}", flush=True)
    df["md5"] = md5s

    md = ["# Duplicate detection (step 3: measurements only)\n"]
    add = md.append
    add(f"Images analysed: {N:,}. Excluded outlier: {len(EXCLUDED)} "
        "(the `.png` pepper-fruit photo, see `reports/audit.md`). "
        "Generated by `src/dataset/duplicates.py`.\n")

    # exact duplicates
    g = df.groupby("md5").agg(n=("path", "size"), n_cls=("cls", "nunique"),
                              n_split=("split", "nunique"))
    dup = g[g["n"] > 1]
    add("## 1. Exact duplicates (identical file bytes)\n")
    add(f"Groups with more than one file: {len(dup):,}, covering {int(dup['n'].sum()):,} files "
        f"({int(dup['n'].sum() - len(dup)):,} redundant copies). "
        f"Groups spanning more than one class: {int((dup['n_cls'] > 1).sum()):,}. "
        f"Groups spanning both train and val: {int((dup['n_split'] > 1).sum()):,}.\n")

    # near duplicates: nearest neighbours over 8 dihedral transforms
    rgb = thumbs.astype(np.float32)
    gray32 = rgb @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
    gray16 = gray32.reshape(N, 16, 2, 16, 2).mean(axis=(2, 4)).astype(np.float32)
    G = torch.from_numpy(gray16)
    A = G.reshape(N, -1)
    a2 = (A ** 2).sum(1)
    found = []
    for t in range(8):
        Bt = tf_torch(G, t).reshape(N, -1).contiguous()
        b2 = (Bt ** 2).sum(1)
        for i0 in range(0, N, CHUNK):
            i1 = min(i0 + CHUNK, N)
            d2 = a2[i0:i1, None] + b2[None, :] - 2 * (A[i0:i1] @ Bt.T)
            d2.clamp_(min=0)
            if t == 0:
                ar = torch.arange(i0, i1)
                d2[ar - i0, ar] = float("inf")
            v, j = torch.topk(d2, TOPK, dim=1, largest=False)
            rms = (v / 256).sqrt()
            ii = torch.arange(i0, i1)[:, None].expand_as(j)
            keep = rms <= RMS_KEEP
            found.append(np.stack([ii[keep].numpy(), j[keep].numpy(),
                                   np.full(int(keep.sum()), t), rms[keep].numpy()], axis=1))
        print(f"  transform {t} done", flush=True)
    cand = pd.DataFrame(np.concatenate(found), columns=["i", "j", "t", "rms"])
    cand[["i", "j", "t"]] = cand[["i", "j", "t"]].astype(int)
    cand["lo"], cand["hi"] = cand[["i", "j"]].min(axis=1), cand[["i", "j"]].max(axis=1)
    cand = cand.sort_values("rms").drop_duplicates(["lo", "hi"]).reset_index(drop=True)

    # verify on the colour thumbnails (mean abs diff, 0-255 scale)
    mad = np.zeros(len(cand), dtype=np.float32)
    for t in range(8):
        sel = np.flatnonzero(cand["t"].to_numpy() == t)
        for s in range(0, len(sel), 20000):
            part = sel[s:s + 20000]
            a = thumbs[cand["i"].to_numpy()[part]].astype(np.int16)
            b = tf_np(thumbs[cand["j"].to_numpy()[part]], t).astype(np.int16)
            mad[part] = np.abs(a - b).mean(axis=(1, 2, 3))
    cand["mad32"] = mad
    cand["same_class"] = df["cls"].to_numpy()[cand["i"]] == df["cls"].to_numpy()[cand["j"]]
    cand["same_split"] = df["split"].to_numpy()[cand["i"]] == df["split"].to_numpy()[cand["j"]]
    cand["md5_equal"] = df["md5"].to_numpy()[cand["i"]] == df["md5"].to_numpy()[cand["j"]]
    cand["identity"] = cand["t"] == 0
    cand["bin"] = pd.cut(cand["rms"], BIN_EDGES, right=False)
    cand.to_csv(scratch / "candidate_pairs.csv", index=False)
    df.to_csv(scratch / "images.csv", index=False)
    print(f"candidate pairs (rms <= {RMS_KEEP}): {len(cand):,}", flush=True)

    add("## 2. Near duplicates: nearest-neighbour distances\n")
    add(f"Each image was compared with the 8 flips/rotations of every other image; the "
        f"{TOPK} nearest per transform were kept if their grayscale RMS distance "
        f"(0-255 scale) was at most {RMS_KEEP:g}. Unique unordered pairs kept: {len(cand):,}. "
        "`mad32` is the mean absolute difference on 32x32 colour thumbnails.\n")
    rows = []
    for b, grp in cand.groupby("bin", observed=True):
        rows.append([str(b), f"{len(grp):,}", f"{int(grp['same_class'].sum()):,}",
                     f"{int((~grp['same_class']).sum()):,}",
                     f"{int((~grp['same_split']).sum()):,}",
                     f"{int((~grp['identity']).sum()):,}",
                     f"{int(grp['md5_equal'].sum()):,}", f"{grp['mad32'].median():.2f}"])
    add(md_table(["RMS bin", "Pairs", "Same class", "Cross class", "Cross split (train/val)",
                  "Found via flip/rotation", "Byte-identical", "Median mad32"], rows))
    add("")

    # the " copy" files and same-name repeats from step 2
    by = {}
    for idx, (c, k) in enumerate(zip(df["cls"], df["key"])):
        by.setdefault((c, k), []).append(idx)
    copy_rows, no_base = [], 0
    for idx, (c, k) in enumerate(zip(df["cls"], df["key"])):
        if k.endswith(" copy"):
            base = by.get((c, k[:-5].strip()))
            if not base:
                no_base += 1
                continue
            m, t = best_mad(thumbs, idx, base[0])
            copy_rows.append((m, t, df["md5"][idx] == df["md5"][base[0]],
                              df["split"][idx] != df["split"][base[0]]))
    add("## 3. Files named `... copy`\n")
    n_copy = len(copy_rows) + no_base
    add(f"Files whose name ends in ` copy`: {n_copy:,}. With a same-class counterpart "
        f"(same name without ` copy`): {len(copy_rows):,}. Without a counterpart: {no_base:,}.\n")
    if copy_rows:
        cm = np.array([r[0] for r in copy_rows])
        add(f"Counterpart pairs: byte-identical {sum(r[2] for r in copy_rows):,}; "
            f"in different splits {sum(r[3] for r in copy_rows):,}; best-transform mad32 "
            f"min {cm.min():.2f}, median {np.median(cm):.2f}, max {cm.max():.2f}; "
            f"pairs with mad32 <= 2: {int((cm <= 2).sum()):,}.\n")

    rep = [v for v in by.values() if len(v) > 1]
    add("## 4. Same-class repeated original names (from step 2)\n")
    if rep:
        rr = []
        for v in rep:
            m, t = best_mad(thumbs, v[0], v[1])
            rr.append((df["cls"][v[0]], df["key"][v[0]], len(v), df["md5"][v[0]] == df["md5"][v[1]],
                       m, df["split"][v[0]] != df["split"][v[1]]))
        add(f"{len(rr):,} names repeat inside one class. Byte-identical: "
            f"{sum(r[3] for r in rr):,}. Best-transform mad32 <= 2: "
            f"{sum(r[4] <= 2 for r in rr):,}. Spanning train and val: {sum(r[5] for r in rr):,}.\n")
        add(md_table(["Class", "Name", "Files", "Byte-identical", "mad32", "Cross split"],
                     [[c, k, n, e, f"{m:.2f}", x] for c, k, n, e, m, x in rr[:12]]))
        add("")

    # visual check montages (scratch only)
    rng = np.random.default_rng(SEED)
    made = []
    for b, grp in cand.groupby("bin", observed=True):
        take = grp.iloc[rng.permutation(len(grp))[:8]]
        canvas = Image.new("RGB", (4 * 264, 2 * 160), "white")
        draw = ImageDraw.Draw(canvas)
        for n, r in enumerate(take.itertuples()):
            x, y = (n % 4) * 264, (n // 4) * 160
            for k, idx in enumerate((r.i, r.j)):
                with Image.open(root / rels[idx]) as im:
                    canvas.paste(im.convert("RGB").resize((128, 128)), (x + k * 132, y))
            draw.text((x, y + 130), f"rms {r.rms:.2f} mad {r.mad32:.1f} t{r.t}", fill="black")
            draw.text((x, y + 142), f"{'same' if r.same_class else 'DIFF'} class", fill="black")
        name = scratch / f"montage_rms_{str(b).replace(', ', '_').strip('[)')}.png"
        canvas.save(name)
        made.append(name.name)
    add("## 5. Visual check\n")
    add("Random pairs from each RMS bin (seed 42) were rendered to the scratch folder for "
        "manual inspection: " + ", ".join(f"`{m}`" for m in made) + ".\n")

    (reports / "duplicates.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote", reports / "duplicates.md", flush=True)


if __name__ == "__main__":
    main()
