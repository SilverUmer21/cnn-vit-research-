# Checks the split manifest and writes the split report. Exits with 1 if a check fails.
# Usage: python -I src/dataset/check_splits.py <manifest_csv> <data_root> <report_md>
import hashlib
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import pandas as pd

COLUMNS = ["path", "label", "group_id", "split"]
SPLITS = ["train", "val", "test"]
TARGET = {"train": 80.0, "val": 10.0, "test": 10.0}
TOLERANCE = 1.0   # percentage points
EXPECTED_EXCLUDED = {  # documented in reports/audit.md: not a lab leaf image
    "train/Pepper,_bell___healthy/42f083e2-272d-4f83-ad9a-573ee90e50ec___"
    "Screen Shot 2015-05-06 at 4.01.13 PM.png",
}


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(lines)


def md5_of(path):
    return hashlib.md5(path.read_bytes()).hexdigest()


def main():
    manifest_path, root, report = Path(sys.argv[1]), Path(sys.argv[2]).resolve(), Path(sys.argv[3])
    m = pd.read_csv(manifest_path, dtype=str, keep_default_na=False)
    n = len(m)
    checks = []

    def record(name, ok, detail):
        checks.append((name, ok, detail))
        print(f"[{'PASS' if ok else 'FAIL'}] {name}: {detail}", flush=True)

    # 1. structure
    ok = list(m.columns) == COLUMNS and set(m["split"]) == set(SPLITS)
    record("Columns and split names", ok,
           f"columns {list(m.columns)}; split values {sorted(set(m['split']))}")

    # 2. duplicate paths
    dup = int(m["path"].duplicated().sum())
    record("No path listed twice", dup == 0, f"{dup} duplicated paths")

    # 3. coverage against the disk
    on_disk = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}
    listed = set(m["path"])
    missing = sorted(listed - on_disk)
    unlisted = sorted(on_disk - listed)
    record("Every listed file exists", not missing, f"{len(missing)} missing")
    record("Every image on disk is listed (except the documented exclusion)",
           set(unlisted) == EXPECTED_EXCLUDED,
           f"{len(unlisted)} unlisted file(s): {unlisted[:3]}")

    # 4. label vs folder
    folder = m["path"].str.split("/").str[1]
    bad_label = int((folder != m["label"]).sum())
    record("Label matches the class folder", bad_label == 0, f"{bad_label} mismatches")

    # 5. group overlap
    per_group_split = m.groupby("group_id")["split"].nunique()
    per_group_label = m.groupby("group_id")["label"].nunique()
    n_overlap = int((per_group_split > 1).sum())
    record("Zero group overlap between train/val/test", n_overlap == 0,
           f"{n_overlap} groups appear in more than one split (of {len(per_group_split):,} groups)")
    n_mixed = int((per_group_label > 1).sum())
    record("Every group has a single label", n_mixed == 0, f"{n_mixed} mixed-label groups")

    # 6. byte-identical files across splits (independent of grouping)
    with ThreadPoolExecutor(max_workers=8) as pool:
        m["md5"] = list(pool.map(md5_of, [root / p for p in m["path"]]))
    cross = int((m.groupby("md5")["split"].nunique() > 1).sum())
    record("No byte-identical files across splits", cross == 0,
           f"{cross} identical-file groups span more than one split")

    # 7. class proportions
    counts = m.pivot_table(index="label", columns="split", values="path", aggfunc="count",
                           fill_value=0)[SPLITS]
    counts["total"] = counts.sum(axis=1)
    share = counts[SPLITS].div(counts["total"], axis=0) * 100
    dev = (share - pd.Series(TARGET)).abs()
    worst = float(dev.to_numpy().max())
    record(f"Class proportions within {TOLERANCE:g} point of 80/10/10", worst <= TOLERANCE,
           f"largest deviation {worst:.2f} points")

    # report
    sizes = m.groupby("group_id").size()
    multi = sizes[sizes > 1]
    orig = m["path"].str.split("/").str[0]
    span_shipped = int((m.assign(o=orig).groupby("group_id")["o"].nunique() > 1).sum())
    overall = m["split"].value_counts()
    md = ["# Split report\n"]
    add = md.append
    add("Generated by `src/dataset/check_splits.py` from `splits/manifest.csv`.\n")

    add("## 1. How the split was made\n")
    add(f"- All {n:,} images from the shipped `train/` and `val/` folders were pooled (the shipped "
        "split was ignored; it has no test set and leaked, see below).\n"
        "- One image was excluded: the `.png` pepper-fruit photo, which is not a lab leaf image "
        "(see `reports/audit.md`). The one `.jpeg` file is a normal leaf and is kept.\n"
        "- Byte-identical images and near-duplicates (same class, very similar thumbnails; "
        "`reports/duplicates.md`, `reports/groups.md`) share a `group_id`. "
        f"{len(multi):,} groups have 2+ images, covering {int(multi.sum()):,} images; the largest "
        f"has {int(multi.max())}. Every other image is its own group.\n"
        "- Stratified, grouped 10-fold split (`StratifiedGroupKFold`, seed 42): one fold is "
        "test, one is val, eight are train. Whole groups stay together.\n"
        "- `path` is relative to the `PlantVillage` data folder. The `train/` or `val/` at the "
        "start of a path is only where the file physically sits, not its split.\n")

    add("## 2. Checks\n")
    add(md_table(["Check", "Result", "Detail"],
                 [[nm, "PASS" if ok else "**FAIL**", d] for nm, ok, d in checks]))
    add("")

    add("## 3. Split sizes\n")
    add(md_table(["Split", "Images", "Share", "Groups"],
                 [[s, f"{overall[s]:,}", f"{100 * overall[s] / n:.2f}%",
                   f"{m[m['split'] == s]['group_id'].nunique():,}"] for s in SPLITS]))
    add("")

    add("## 4. Class proportions per split\n")
    rows = []
    for c in counts.index:
        rows.append([c] + [f"{int(counts.loc[c, s]):,}" for s in SPLITS] +
                    [f"{int(counts.loc[c, 'total']):,}"] +
                    [f"{share.loc[c, s]:.1f}%" for s in SPLITS])
    add(md_table(["Class", "train", "val", "test", "Total", "train %", "val %", "test %"], rows))
    add("")
    add(f"Largest per-class deviation from 80/10/10: {worst:.2f} percentage points.\n")

    add("## 5. Notes and limits\n")
    small = counts.sort_values("total").head(5)
    add("- **Small test sets.** Smallest classes: " +
        ", ".join(f"`{c}` (train {int(r['train'])}, val {int(r['val'])}, test {int(r['test'])})"
                  for c, r in small.iterrows()) +
        f". The smallest test set has {int(counts['test'].min())} images, so per-class scores "
        "for these classes are noisy; a single error moves them by several points.\n")
    add(f"- **The shipped split leaked.** {span_shipped} groups had images in both the shipped "
        "`train/` and `val/` folders (byte-identical files and near-duplicates). This split "
        "has none.\n")
    add("- **Limit of duplicate detection.** Grouping uses image similarity. The same leaf "
        "photographed from a clearly different angle is not reliably detected, so some leaf-level "
        "similarity across splits may remain. Look-alike leaves can also be grouped together; "
        "that only makes the split slightly more conservative.\n")
    add("- **Image size.** All images are 256x256. MobileViT-XS (256) uses them as they are; "
        "MobileNetV2 (224) needs a resize, so FLOPs and latency reflect architecture and input "
        "size together.\n")

    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {report}")
    sys.exit(0 if all(ok for _, ok, _ in checks) else 1)


if __name__ == "__main__":
    main()
