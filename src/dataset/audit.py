# Audit of the PlantVillage folder: counts, image checks and filename analysis.
# Read-only on the data. Usage: python -I src/dataset/audit.py <data_root> <out_markdown>
import re
import sys
import warnings
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import pandas as pd
from PIL import Image

PROPOSAL_TOTAL = 54306
KAGGLE_LISTING_TOTAL = 54303
IMAGE_EXTS = {".jpg", ".jpeg", ".png"}
FORMAT_FOR_EXT = {".jpg": "JPEG", ".jpeg": "JPEG", ".png": "PNG"}

NAME_RE = re.compile(
    r"^(?P<uuid>[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})"
    r"___(?P<orig>.+)$"
)
PREFIX_RE = re.compile(r"^(?P<prefix>.*?)[ _]?(?P<num>\d+)$")
AUG_PATTERNS = {
    "flip": re.compile(r"flip", re.I),
    "rotation/deg": re.compile(r"rotat|\d\s*deg|_deg", re.I),
    "mirror": re.compile(r"mirror", re.I),
    "copy": re.compile(r"copy", re.I),
    "'new' marker": re.compile(r"(^|[ _])new", re.I),
    "(n) suffix": re.compile(r"\(\d+\)"),
}


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(lines)


def inspect_image(path):
    info = {"ok": True, "error": "", "format": "", "mode": "", "width": 0, "height": 0,
            "bytes": path.stat().st_size}
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            with Image.open(path) as im:
                info["format"], info["mode"] = im.format, im.mode
                info["width"], info["height"] = im.size
                im.load()
    except Exception as exc:  # corrupt/truncated/unreadable
        info["ok"] = False
        info["error"] = f"{type(exc).__name__}: {exc}"
    return info


def main():
    root = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve()
    if not root.is_dir():
        sys.exit(f"not a directory: {root}")
    if root == out or root in out.parents:
        sys.exit("refusing to write inside the data root")

    # scan
    paths = sorted(p for p in root.rglob("*") if p.is_file())
    rows, unexpected = [], []
    for p in paths:
        rel = p.relative_to(root)
        if len(rel.parts) != 3:
            unexpected.append(rel.as_posix())
            continue
        split, cls, fname = rel.parts
        rows.append({"path": rel.as_posix(), "split": split, "cls": cls, "fname": fname})
    df = pd.DataFrame(rows)
    print(f"files found: {len(paths)}  (unexpected depth: {len(unexpected)})", flush=True)

    # image inspection (read-only)
    full = [root / p for p in df["path"]]
    results = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        for i, res in enumerate(pool.map(inspect_image, full), 1):
            results.append(res)
            if i % 5000 == 0:
                print(f"  inspected {i}/{len(full)}", flush=True)
    df = pd.concat([df, pd.DataFrame(results)], axis=1)

    df["ext"] = df["fname"].map(lambda f: Path(f).suffix.lower())
    df["crop"] = df["cls"].map(lambda c: c.split("___")[0])
    df["condition"] = df["cls"].map(lambda c: c.split("___", 1)[1] if "___" in c else "")

    # filename parsing
    stems = df["fname"].map(lambda f: Path(f).stem)
    parsed = stems.map(NAME_RE.match)
    df["has_pattern"] = parsed.map(lambda m: m is not None)
    df["uuid"] = parsed.map(lambda m: m.group("uuid").lower() if m else "")
    # names without a UUID prefix: the whole stem is the original name
    df["orig"] = [m.group("orig") if m else s for m, s in zip(parsed, stems)]
    df["key"] = df["orig"].map(lambda s: re.sub(r"\s+", " ", s).strip().lower())
    pm = df["orig"].map(PREFIX_RE.match)
    df["prefix"] = pm.map(lambda m: m.group("prefix").strip() if m else "")

    n_total = len(df)
    n_readable = int(df["ok"].sum())
    md = []
    add = md.append

    add("# Dataset audit: PlantVillage (as received)\n")
    add(f"Data root: `{root.name}/` (read-only; nothing in it was modified). "
        "Generated by `src/dataset/audit.py`.\n")

    # 1. reconciliation
    ext_counts = df["ext"].value_counts()
    add("## 1. Image count reconciliation\n")
    add(md_table(["Source", "Count"], [
        ["Proposal", f"{PROPOSAL_TOTAL:,}"],
        ["Kaggle listing (per dataset description)", f"~{KAGGLE_LISTING_TOTAL:,}"],
        ["Files found in folder (all types)", f"{len(paths):,}"],
        ["Files at expected depth split/class/file", f"{n_total:,}"],
        ["Files at unexpected depth / stray", f"{len(unexpected):,}"],
        ["Readable images (fully decoded)", f"{n_readable:,}"],
        ["Unreadable / corrupt", f"{n_total - n_readable:,}"],
    ]))
    add("")
    add(md_table(["Extension (lowercased)", "Files"],
                 [[e, f"{c:,}"] for e, c in ext_counts.items()]))
    add("")
    add(f"Difference vs proposal: {n_total - PROPOSAL_TOTAL:+,}. "
        f"Difference vs Kaggle listing: {n_total - KAGGLE_LISTING_TOTAL:+,}.\n")
    if unexpected:
        add("Stray files:\n")
        add("\n".join(f"- `{u}`" for u in unexpected[:50]))
        add("")

    # 2. structure
    splits = sorted(df["split"].unique())
    classes = sorted(df["cls"].unique())
    per = df.pivot_table(index="cls", columns="split", values="path", aggfunc="count",
                         fill_value=0)
    per["total"] = per.sum(axis=1)
    add("## 2. Structure and class balance\n")
    add(f"Top-level folders: {', '.join(f'`{s}`' for s in splits)}. "
        f"Classes: {len(classes)}. Crops: {df['crop'].nunique()}. "
        f"Healthy classes: {int((df.drop_duplicates('cls')['condition'].str.lower() == 'healthy').sum())}. "
        f"Disease classes: {int((df.drop_duplicates('cls')['condition'].str.lower() != 'healthy').sum())}.\n")
    per_split_classes = {s: set(df[df['split'] == s]['cls']) for s in splits}
    same = all(per_split_classes[s] == set(classes) for s in splits)
    add(f"Every split contains the same class folders: **{same}**.\n")
    tot_by_split = df["split"].value_counts()
    add(md_table(["Split", "Files", "Share"],
                 [[s, f"{tot_by_split[s]:,}", f"{100 * tot_by_split[s] / n_total:.2f}%"]
                  for s in splits]))
    add("")
    hdr = ["Class"] + splits + ["Total", f"{splits[-1]} share"]
    rws = []
    for c in classes:
        r = per.loc[c]
        rws.append([c] + [f"{int(r[s]):,}" for s in splits] + [f"{int(r['total']):,}",
                   f"{100 * r[splits[-1]] / r['total']:.1f}%"])
    add(md_table(hdr, rws))
    add("")
    smallest = per["total"].sort_values().head(5)
    add("Smallest classes: " + ", ".join(f"`{c}` ({int(n):,})" for c, n in smallest.items()) + ".\n")

    # 3. image properties
    ok = df[df["ok"]]
    add("## 3. Image properties\n")
    add("Formats (actual, from file content): " +
        ", ".join(f"{k}: {v:,}" for k, v in ok["format"].value_counts().items()) + "\n")
    add("Colour modes: " +
        ", ".join(f"{k}: {v:,}" for k, v in ok["mode"].value_counts().items()) + "\n")
    sizes = ok.groupby(["width", "height"]).size().sort_values(ascending=False)
    add(md_table(["Width x Height", "Files"],
                 [[f"{w} x {h}", f"{n:,}"] for (w, h), n in sizes.head(10).items()]))
    add("")
    add(f"Distinct sizes: {len(sizes):,}. Width range {int(ok['width'].min())}-{int(ok['width'].max())}, "
        f"height range {int(ok['height'].min())}-{int(ok['height'].max())}. "
        f"File size bytes: min {int(ok['bytes'].min()):,}, median {int(ok['bytes'].median()):,}, "
        f"max {int(ok['bytes'].max()):,}.\n")
    mismatch = ok[[FORMAT_FOR_EXT.get(e, "?") != f for e, f in zip(ok["ext"], ok["format"])]]
    add(f"Files whose extension does not match their real format: {len(mismatch):,}.\n")
    bad = df[~df["ok"]]
    if len(bad):
        add("Unreadable files:\n")
        add(md_table(["Path", "Error"], [[r.path, r.error] for r in bad.head(50).itertuples()]))
        add("")
    else:
        add("No unreadable or corrupt images.\n")

    # 4. odd files
    odd = df[(df["ext"] != ".jpg") | (~df["ext"].isin(IMAGE_EXTS))]
    add("## 4. Files with unusual extensions\n")
    if len(odd):
        add(md_table(["Path", "Real format", "Mode", "Size (WxH)", "Bytes"],
                     [[r.path, r.format, r.mode, f"{r.width} x {r.height}", f"{r.bytes:,}"]
                      for r in odd.itertuples()]))
    else:
        add("None.")
    add("")
    add("Inspection and decision: the `.jpeg` is an ordinary tomato leaf on a grey background "
        "and is kept. The `.png` is an RGBA outdoor photo of an orange pepper fruit with dark "
        "lesions and leaves behind it, labelled `Pepper,_bell___healthy`. It is not a lab leaf "
        "image, so it is **excluded** from the dataset used for splitting "
        f"({n_total - 1:,} images remain). It is the only exclusion.\n")

    # 5. filename analysis
    add("## 5. Filename analysis\n")
    add(f"Pattern `<uuid>___<original-name>.<ext>`: {int(df['has_pattern'].sum()):,} of "
        f"{n_total:,} match.\n")
    nomatch = df[~df["has_pattern"]]
    if len(nomatch):
        add("Files without a UUID prefix, by class and split:\n")
        by_cls = nomatch.groupby(["cls", "split"]).size().reset_index(name="n")
        add(md_table(["Class", "Split", "Files"],
                     [[r.cls, r.split, f"{r.n:,}"] for r in by_cls.itertuples()]))
        add("")
        add("Examples: " + ", ".join(f"`{f}`" for f in nomatch["fname"].head(5)) + "\n")
    pat = df[df["has_pattern"]]
    dup_uuid = pat["uuid"].value_counts()
    add(f"Distinct UUIDs: {pat['uuid'].nunique():,}. UUIDs used by more than one file: "
        f"{int((dup_uuid > 1).sum()):,}.\n")

    # original names (case/space-normalised, extension removed); files without a UUID
    # use their whole stem. Repeats are analysed across the dataset and within a class.
    by_key = df.groupby("key").agg(n=("path", "size"), n_cls=("cls", "nunique"))
    add(f"Distinct original names over all {n_total:,} files: {len(by_key):,}. "
        f"Names used by more than one file: {int((by_key['n'] > 1).sum()):,}, of which "
        f"{int((by_key['n_cls'] > 1).sum()):,} span more than one class.\n")
    same = df.groupby(["cls", "key"]).agg(n=("path", "size"), n_split=("split", "nunique"))
    rep = same[same["n"] > 1]
    add(f"Within a single class, original names used by more than one file: {len(rep):,}, "
        f"covering {int(rep['n'].sum()):,} files. Largest repeat count: {int(same['n'].max())}. "
        f"Of these names, {int((rep['n_split'] > 1).sum()):,} appear in both train and val.\n")
    if len(rep):
        ex = rep.reset_index().sort_values(["n", "cls", "key"], ascending=[False, True, True])
        add("Examples of same-class repeats:\n")
        add(md_table(["Class", "Original name", "Files", "Splits"],
                     [[r.cls, r.key, r.n, r.n_split] for r in ex.head(10).itertuples()]))
        add("")
    if "train" in splits and "val" in splits:
        train_pairs = set(zip(df[df["split"] == "train"]["cls"], df[df["split"] == "train"]["key"]))
        val_rows = df[df["split"] == "val"]
        n_hit = sum((c, k) in train_pairs for c, k in zip(val_rows["cls"], val_rows["key"]))
        add(f"Validation files whose (class, original name) also appears in train: {n_hit:,} of "
            f"{len(val_rows):,} ({100 * n_hit / max(len(val_rows), 1):.2f}%).\n")

    add("Augmentation-style tokens in filenames (file counts, with examples):\n")
    aug_rows = []
    for name, rx in AUG_PATTERNS.items():
        hit = df[df["fname"].map(lambda f, rx=rx: bool(rx.search(f)))]
        aug_rows.append([name, f"{len(hit):,}",
                         "; ".join(f"`{f}`" for f in hit["fname"].head(3))])
    add(md_table(["Token", "Files", "Examples"], aug_rows))
    add("")
    pref = pat["prefix"].value_counts()
    add(f"Original-name prefixes (text before the trailing number): {len(pref):,} distinct. "
        "Most common:\n")
    add(md_table(["Prefix", "Files"], [[p, f"{n:,}"] for p, n in pref.head(15).items()]))
    add("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {out}", flush=True)


if __name__ == "__main__":
    main()
